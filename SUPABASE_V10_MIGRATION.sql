-- V10 LIVE LEARNING additions
create table if not exists public.bot_prediction_outcomes (
  id bigint generated by default as identity primary key,
  predicted_at timestamptz not null default now(),
  settled_at timestamptz,
  symbol text not null,
  entry_price numeric not null,
  expected_rate numeric,
  score numeric,
  net_edge numeric,
  v7_score numeric,
  learning_trade_count integer,
  learning_win_rate numeric,
  learning_avg_pnl_rate numeric,
  executed boolean not null default false,
  order_id text,
  return_5m numeric,
  return_15m numeric,
  return_30m numeric,
  return_60m numeric,
  status text not null default 'PENDING'
    check (status in ('PENDING','SETTLED','CANCELLED'))
);
create index if not exists bot_prediction_outcomes_symbol_time_idx
  on public.bot_prediction_outcomes(symbol, predicted_at desc);
create index if not exists bot_prediction_outcomes_pending_idx
  on public.bot_prediction_outcomes(status, predicted_at);

-- RLS policies for the publishable key. Run only if your project has RLS enabled.
alter table public.bot_prediction_outcomes enable row level security;
drop policy if exists bot_prediction_select on public.bot_prediction_outcomes;
drop policy if exists bot_prediction_insert on public.bot_prediction_outcomes;
drop policy if exists bot_prediction_update on public.bot_prediction_outcomes;
create policy bot_prediction_select on public.bot_prediction_outcomes for select to anon, authenticated using (true);
create policy bot_prediction_insert on public.bot_prediction_outcomes for insert to anon, authenticated with check (true);
create policy bot_prediction_update on public.bot_prediction_outcomes for update to anon, authenticated using (true) with check (true);
